    async function hostRequest(action, payload, signal) {
      const carrier = globalThis.__DSH_TRANSPORT__?.fetch
      const fetcher = carrier || globalThis.fetch.bind(globalThis)
      let response
      try {
        response = await fetcher(requestUrl(), {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ action, ...(payload || {}) }),
          signal,
        })
      } catch (error) {
        throw new Error(error instanceof Error ? error.message : String(error))
      }
      let answer
      try {
        answer = await response.json()
      } catch {
        throw new Error(`DSH Host returned HTTP ${response.status}.`)
      }
      if (!response.ok || !answer || answer.ok !== true) {
        throw new Error(answer?.error?.message || `DSH Host returned HTTP ${response.status}.`)
      }
      return answer.value
    }

